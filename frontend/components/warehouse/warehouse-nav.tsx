"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const items = [
  { href: "/warehouse", label: "Overview", exact: true, icon: <IconHome /> },
  { href: "/warehouse/stock", label: "Stock", exact: false, icon: <IconBox /> },
  { href: "/warehouse/pick", label: "Pick", exact: false, icon: <IconHand /> },
  { href: "/warehouse/pack", label: "Pack", exact: false, icon: <IconPackage /> },
  { href: "/warehouse/receiving", label: "Receiving", exact: false, icon: <IconTruck /> },
  { href: "/warehouse/stocktake", label: "Stocktake", exact: false, icon: <IconClipboard /> },
  { href: "/warehouse/print", label: "Print", exact: false, icon: <IconPrinter /> },
];

export function WarehouseNav({ onNavigate }: { onNavigate?: () => void }) {
  const pathname = usePathname();
  return (
    <ul className="space-y-0.5">
      {items.map((item) => {
        const active = item.exact ? pathname === item.href : pathname.startsWith(item.href);
        return (
          <li key={item.href}>
            <Link
              href={item.href}
              onClick={onNavigate}
              className={`flex items-center gap-2.5 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
                active
                  ? "bg-primary/15 font-semibold text-primary"
                  : "text-muted hover:bg-surface-2 hover:text-foreground"
              }`}
            >
              <span className={active ? "text-primary" : "text-muted"}>{item.icon}</span>
              {item.label}
              {active && (
                <span className="ml-auto h-1.5 w-1.5 rounded-full bg-primary" aria-hidden />
              )}
            </Link>
          </li>
        );
      })}
    </ul>
  );
}

export function WarehouseBottomNav() {
  const pathname = usePathname();
  const compact = items.filter((item) =>
    ["/warehouse", "/warehouse/pick", "/warehouse/pack", "/warehouse/stock"].includes(item.href),
  );
  return (
    <nav className="grid grid-cols-4">
      {compact.map((item) => {
        const active = item.exact ? pathname === item.href : pathname.startsWith(item.href);
        return (
          <Link
            key={item.href}
            href={item.href}
            className={`flex flex-col items-center gap-0.5 py-2 text-[11px] font-semibold transition-colors ${
              active ? "text-primary" : "text-muted"
            }`}
          >
            {item.icon}
            {item.label}
          </Link>
        );
      })}
    </nav>
  );
}

